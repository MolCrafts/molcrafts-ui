import { cp, mkdir, readFile, writeFile } from "node:fs/promises";
import { webLightTheme, webDarkTheme } from "@fluentui/react-theme";
import postcss from "postcss";
import selectorParser from "postcss-selector-parser";

const root = new URL("../", import.meta.url);
const pkg = new URL("packages/web-components/", root);
const catalog = JSON.parse(await readFile(new URL("components.json", pkg), "utf8"));
const upstream = JSON.parse(await readFile(new URL("node_modules/@fluentui/web-components/custom-elements.json", root), "utf8"));
const header = "// Generated by npm run generate:web-components. Do not edit.\n";
await mkdir(new URL("src/", pkg), { recursive: true });

const imports = catalog.components.flatMap(c => [c.class, `${c.class}Definition`]);
let source = header + `import { css, FASTElement, type Constructable } from "@microsoft/fast-element";\nimport { ${imports.join(", ")} } from "@fluentui/web-components";\n`;
source += `export { ${catalog.components.map(c => c.class).join(", ")} };\n`;
source += "export const managedComponents = [\n" + catalog.components.map(c =>
  `  { tag: ${JSON.stringify(c.tag)}, element: ${c.class}, definition: ${c.class}Definition },`).join("\n") + "\n] as const;\n";
source += `
const reducedMotionStyles = css\`
  @media (prefers-reduced-motion: reduce) {
    *, *::before, *::after { animation: none !important; transition: none !important; }
  }
\`;
export async function registerMolcraftsComponents(): Promise<void> {
  if (!globalThis.customElements) throw new Error("Register MolCrafts Web Components in the browser, after hydration.");
  for (const { tag, element, definition } of managedComponents) {
    const existing = customElements.get(tag);
    if (existing && existing !== element) throw new Error(\`Conflicting Web Component registration for \$\{tag\}. Use one Fluent version per page.\`);
    if (!existing) {
      const styles = definition.styles ? (Array.isArray(definition.styles) ? definition.styles : [definition.styles]) : [];
      await FASTElement.define<Constructable<HTMLElement>>(element, { ...definition, styles: [...styles, reducedMotionStyles] });
    }
  }
}
declare global {
  interface HTMLElementTagNameMap {
${catalog.components.map(c => `    "${c.tag}": ${c.class};`).join("\n")}
  }
}
`;
await writeFile(new URL("src/components.ts", pkg), source);

const icons = {};
for (const name of catalog.icons) {
  icons[name] = (await readFile(new URL(`node_modules/@fluentui/svg-icons/icons/${name}_20_regular.svg`, root), "utf8"))
    .replace("<svg ", '<svg aria-hidden="true" fill="currentColor" ');
}
await writeFile(new URL("src/icons.ts", pkg), header +
  `export const fluentIcons = ${JSON.stringify(icons, null, 2)} as const;\nexport type FluentIconName = keyof typeof fluentIcons;\n`);

const declarations = catalog.components.map(c => {
  const declaration = upstream.modules.flatMap(m => m.declarations ?? []).find(d => d.name === c.class && d.customElement);
  if (!declaration) throw new Error(`Missing upstream manifest for ${c.tag}`);
  return JSON.parse(JSON.stringify({ ...declaration, tagName: c.tag }), (key, value) => {
    if (value && typeof value === "object" && value.module) {
      return { ...value, package: "@fluentui/web-components" };
    }
    return value;
  });
});
const manifest = {
  schemaVersion: "1.0.0",
  modules: [{ kind: "javascript-module", path: "dist/index.js", declarations,
    exports: catalog.components.flatMap(c => [
      { kind: "js", name: c.class, declaration: { name: c.class, module: "dist/index.js" } },
      { kind: "custom-element-definition", name: c.tag, declaration: { name: c.class, module: "dist/index.js" } },
    ]),
  }],
};
await writeFile(new URL("custom-elements.json", pkg), JSON.stringify(manifest, null, 2) + "\n");

const block = (selector, theme) => `${selector} {\n` + Object.entries(theme).map(([name, value]) => `  --${name}: ${value};`).join("\n") + "\n}\n";
await writeFile(new URL("src/fluent-web-theme.css", pkg),
  "/* Generated from the shared Fluent 2 themes. */\n" + block(":where(:root, :host)", webLightTheme) + "\n" + block(".dark, :where(:root, :host).dark", webDarkTheme));

// Document resets outrank :host rules. Mirror only official host rules into the
// document scope, retaining their state/media selectors and Shadow DOM internals.
const hostStyles = [];
for (const component of catalog.components) {
  const name = component.tag.replace("fluent-", "");
  const css = postcss.parse(await readFile(new URL(`node_modules/@fluentui/web-components/dist/esm/${name}/${name}.styles.css`, root), "utf8"));
  css.walkRules(rule => {
    const selectors = rule.selectors.filter(selector => selector.includes(":host"));
    if (!selectors.length) { rule.remove(); return; }
    rule.selector = selectorParser(selectors => {
      selectors.walkPseudos(pseudo => {
        if (pseudo.value === ":host") {
          const inner = pseudo.nodes?.[0]?.nodes.map(node => node.clone()) ?? [];
          pseudo.replaceWith(selectorParser.tag({ value: component.tag }), ...inner);
        } else if (pseudo.value === "::slotted") {
          const inner = pseudo.nodes[0].nodes.map(node => node.clone());
          pseudo.replaceWith(selectorParser.combinator({ value: ">" }), ...inner);
        }
      });
    }).processSync(selectors.join(", "));
  });
  css.walkAtRules(rule => { if (!rule.nodes?.length) rule.remove(); });
  hostStyles.push(css.toString());
}
await writeFile(new URL("src/fluent-host.css", pkg), "/* Generated official host styles; protects custom elements from document resets. */\n" + hostStyles.join("\n"));
for (const name of ["fluent-theme.css", "fluent-foundation.css", "constitution-base.css"]) {
  await cp(new URL(`src/styles/${name}`, root), new URL(`src/${name}`, pkg));
}

if (process.argv.includes("--assets")) {
  await mkdir(new URL("dist/", pkg), { recursive: true });
  for (const name of ["theme.css", "fluent-theme.css", "fluent-foundation.css", "constitution-base.css", "fluent-web-theme.css", "fluent-host.css"]) {
    await cp(new URL(`src/${name}`, pkg), new URL(`dist/${name}`, pkg));
  }
  await cp(new URL("custom-elements.json", pkg), new URL("dist/custom-elements.json", pkg));
}
console.log(`Generated ${catalog.components.length} managed Web Components, manifest, icons, and theme.`);
